"""Generate transport-only types and vendored validation schemas from contracts/."""
from pathlib import Path
import json
import sys

root = Path(__file__).resolve().parents[1]
source = root / 'contracts/algorithm-v1.schema.json'
schema = json.loads(source.read_text())

def type_name(value, language):
    if '$ref' in value: return value['$ref'].split('/')[-1]
    if 'const' in value:
        literal = json.dumps(value['const'])
        return literal if language == 'ts' else 'Literal[' + literal + ']'
    if 'enum' in value:
        values = [json.dumps(item) for item in value['enum']]
        return ' | '.join(values) if language == 'ts' else 'Literal[' + ', '.join(values) + ']'
    if 'anyOf' in value: return ' | '.join(type_name(item, language) for item in value['anyOf'])
    kind = value['type']
    if kind == 'array':
        item = type_name(value['items'], language)
        return f'Array<{item}>' if language == 'ts' else f'list[{item}]'
    if kind == 'object':
        if 'properties' not in value:
            item = type_name(value['additionalProperties'], language)
            return '{ [key: string]: ' + item + ' }' if language == 'ts' else f'dict[str, {item}]'
        if language == 'ts': return '{ ' + '; '.join(key + (': ' if key in value.get('required', value['properties']) else '?: ') + type_name(item, language) for key, item in value['properties'].items()) + ' }'
        return 'dict[str, Json]'
    return ({'null':'null','boolean':'boolean','integer':'number','number':'number','string':'string'} if language == 'ts' else
            {'null':'None','boolean':'bool','integer':'int','number':'float','string':'str'})[kind]

ts = ['// Generated by scripts/generate-algorithm-contracts.py. Do not edit.']
py = ['"""Generated transport types. Author contracts live in algorithms/contracts.py."""',
      'from __future__ import annotations', 'from typing import Literal, TypedDict, TypeAlias',
      'from gear.canonical import JSON as Json']
for name, definition in schema['$defs'].items():
    ts.append('export type ' + name + ' = ' + type_name(definition, 'ts'))
    if name == 'Json': continue
    if definition.get('type') == 'object' and 'properties' in definition:
        required = definition.get('required', list(definition['properties']))
        optional = [key for key in definition['properties'] if key not in required]
        py.append('\nclass ' + ('_' + name + 'Required' if optional else name) + '(TypedDict):')
        py.extend('    ' + key + ': ' + type_name(value, 'py') for key, value in definition['properties'].items() if key in required)
        if not required: py.append('    pass')
        if optional:
            py.append('\nclass ' + name + '(_' + name + 'Required, total=False):')
            py.extend('    ' + key + ': ' + type_name(definition['properties'][key], 'py') for key in optional)
    else: py.append(name + ': TypeAlias = ' + type_name(definition, 'py'))
outputs = {
    'src/domain/algorithm-wire.ts': ('\n'.join(ts)+'\n').encode(),
    'python/gear/refine/wire_types.py': ('\n'.join(py)+'\n').encode(),
    'src/domain/algorithm-v1.schema.json': source.read_bytes(),
    'python/gear/refine/algorithm-v1.schema.json': source.read_bytes(),
    'python/gear/algorithms/limits.py': (
        '"""Generated decision bounds from contracts/algorithm-v1.schema.json."""\n\n'
        + 'MAX_DECISION_OPERATIONS = '
        + str(schema['$defs']['Decision']['properties']['operations']['maxItems'])
        + '\n'
    ).encode(),
}
for name, content in outputs.items():
    target = root / name
    if '--check' in sys.argv:
        if not target.is_file() or target.read_bytes() != content:
            raise SystemExit(name + ' is stale; run npm run generate:contracts')
    else:
        target.write_bytes(content)
